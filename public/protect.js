/*
 * protect.js — ردع بسيط ضد النسخ العرضي لواجهة الموقع
 * ------------------------------------------------------------
 * ملاحظة صريحة ومهمة: أي كود HTML/CSS/JS يُرسَل للمتصفح ليعمل، يستطيع
 * المتصفح نفسه (وأي شخص يستخدمه) قراءته دائماً — عبر "عرض المصدر"،
 * تبويب الشبكة (Network)، أو أدوات المطوّر. لا توجد طريقة تقنية على
 * الواجهة الأمامية (Frontend) تمنع هذا فعلياً بشكل كامل؛ هذا قيد أساسي
 * بطريقة عمل الويب وليس نقص حماية بهذا الكود تحديداً.
 *
 * ما يفعله هذا الملف هو رفع مستوى "الاحتكاك" أمام النسخ العارض غير
 * المقصود (زائر عادي يضغط كليك يمين أو F12 بدون قصد جدي)، ويترك أثراً
 * (تنبيه حقوق الملكية) يُفيد لاحقاً كدليل عند أي إجراء قانوني ضد نسخ
 * الموقع. أي مطوّر مصمم فعلاً على استخراج الكود سيتجاوز هذا بسهولة
 * (Proxy، أدوات خارج المتصفح، تعطيل JS، ...)، لذا الحماية الحقيقية هي:
 *   1) شروط استخدام (Terms of Service) صريحة تمنع النسخ/الزحف الآلي.
 *   2) تسجيل حقوق الملكية الفكرية للمشروع.
 *   3) مراقبة الزحف الآلي على مستوى السيرفر (نُفّذ حدّ معدّل طلبات
 *      أساسي على مسارات API في server.js).
 *   4) عند اكتشاف نسخة مسروقة منشورة فعلياً: تقديم بلاغ DMCA لمزوّد
 *      الاستضافة/المتصفح/محرك البحث الذي يستضيف/يفهرس النسخة.
 */
(function () {
  // منع قائمة الزر الأيمن السريعة (لا تمنع "عرض المصدر" أو أدوات الشبكة)
  document.addEventListener('contextmenu', function (e) {
    e.preventDefault();
  });

  // منع اختصارات لوحة المفاتيح الشائعة لفتح أدوات المطوّر/عرض المصدر
  document.addEventListener('keydown', function (e) {
    const key = (e.key || '').toLowerCase();
    const blockCombo =
      key === 'f12' ||
      (e.ctrlKey && e.shiftKey && ['i', 'j', 'c'].includes(key)) ||
      (e.ctrlKey && key === 'u') ||
      (e.metaKey && e.altKey && ['i', 'j', 'c'].includes(key)); // ماك
    if (blockCombo) e.preventDefault();
  });

  // تنبيه في الكونسول لمن يفتحه فعلاً عبر طرق أخرى (مفيد كدليل/إشعار قانوني)
  try {
    console.log(
      '%cتنبيه: محتوى هذا الموقع وكوده محميان بحقوق الملكية الفكرية.',
      'color:#d33;font-size:16px;font-weight:bold;'
    );
    console.log(
      '%cنسخ أو إعادة نشر الكود المصدري لهذا المشروع دون إذن مخالف لشروط الاستخدام.',
      'color:#555;font-size:12px;'
    );
  } catch (e) {}
})();
